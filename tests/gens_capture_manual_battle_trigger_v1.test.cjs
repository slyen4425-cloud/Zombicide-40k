"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),ctx={};
for(const file of ["battle-bridge-contract-v1.js","lab-ownership-port-v1.js","manual-battle-trigger-v1.js"])vm.runInNewContext(fs.readFileSync("assets/gensrpg/capture/"+file,"utf8"),ctx);
const port=ctx.GensCaptureLabOwnershipPortV1,trigger=ctx.GensCaptureManualBattleTriggerV1.create(port,ctx.GensCaptureBattleBridgeContractV1);
const input={sides:[{creatures:[{instanceId:"hero",hp:10,maxHp:10}],active:["hero"]},{creatures:[{instanceId:"enemy",hp:8,maxHp:8}],active:["enemy"]}]};
assert.equal(trigger.launch("manual-1",input).ready,false);
let starts=0,stops=0,disposes=0;
const provider={protocol:1,version:"1.0.0",capabilities:["battle-trigger"],createBattle:x=>({context:x}),startBattle:()=>starts++,stopBattle:()=>stops++,disposeBattle:()=>disposes++,openCreatureEditor:()=>({}),closeCreatureEditor:()=>{}};
port.install(provider);
const launched=trigger.launch("manual-1",input);assert.equal(launched.ready,true);
assert.equal(launched.session.context.persist,false);assert.equal(launched.session.context.mode,"manual-test");
assert.throws(()=>trigger.launch("manual-2",input),/already active/);
assert.throws(()=>trigger.finish({outcome:"victory",creatures:[]}),/Incomplete/);
assert.equal(trigger.status().active,true);
const completed=trigger.finish({outcome:"victory",creatures:[{instanceId:"hero",hp:10},{instanceId:"enemy",hp:0}]});
assert.equal(completed.persist,false);assert.equal(completed.result.outcome,"victory");
assert.equal(starts,1);assert.equal(stops,1);assert.equal(disposes,1);
assert.equal(trigger.cancel(),false);assert.equal(trigger.launch("manual-3",input).ready,true);
assert.equal(trigger.cancel(),true);assert.equal(stops,2);assert.equal(disposes,2);
port.uninstall(provider);
console.log("Exploration-free manual battle trigger: PASS");
