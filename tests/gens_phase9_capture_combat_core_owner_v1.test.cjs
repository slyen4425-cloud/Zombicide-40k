'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const index=fs.readFileSync(path.join(root,'index.html'));
const moduleBytes=fs.readFileSync(path.join(root,'assets/gensrpg/capture/combat-core-v1.js'));
const blob=s=>crypto.createHash('sha1').update(Buffer.from('blob '+s.length+'\\0')).update(s).digest('hex');
const original={bytes:7950873,blob:'57415a1071475cc10f0c79e092897190577127e8'};
const loader=Buffer.from('<script src="assets/gensrpg/capture/combat-core-v1.js?v=1"></script>\\n');
const start=Buffer.from('const GENS_CAPTURE_BATTLE_TARGETS=[\\n');
const end=Buffer.from('function gensRollLocationEncounter(locationId){\\n');
const header=Buffer.from('// GenSrpG Phase9 Capture battle core - identical legacy source relocation.\\n// Classic script to retain original global lexical/function contract.\\n// BEGIN_CAPTURE_BATTLE_CORE\\n');
const footer=Buffer.from('// END_CAPTURE_BATTLE_CORE\\n');
assert.ok(index.indexOf(loader)>=0,'Capture battle module must have one synchronous loader');
assert.equal(index.indexOf(loader),index.lastIndexOf(loader),'loader is unique');
assert.equal(index.indexOf(start),-1,'old core owner must not remain in HTML');
assert.ok(moduleBytes.subarray(0,header.length).equals(header));
assert.ok(moduleBytes.subarray(-footer.length).equals(footer));
const code=moduleBytes.subarray(header.length,moduleBytes.length-footer.length);
assert.ok(code.subarray(0,start.length).equals(start));
let restored=Buffer.concat([index.subarray(0,index.indexOf(loader)),index.subarray(index.indexOf(loader)+loader.length)]);
const pos=restored.indexOf(end);
assert.ok(pos>0,'restore anchor');
restored=Buffer.concat([restored.subarray(0,pos),code,restored.subarray(pos)]);
assert.equal(restored.length,original.bytes,'byte count restored');
assert.equal(blob(restored),original.blob,'rollback exactly the approved source');
const codeText=code.toString('utf8');
const names=[...codeText.matchAll(/^function (\\w+)\\(/gm)].map(m=>m[1]);
assert.ok(names.length>=35,'physical extraction must own the complete historical core');
assert.ok(names.includes('gensCreateCaptureBattle'));
assert.ok(names.includes('gensCaptureBattleEvaluateVictory'));
assert.ok(names.includes('gensCaptureBattleRecall'));
assert.ok(names.includes('gensCaptureBattleTargets'));
for(const name of names)assert.ok(!index.includes(Buffer.from('function '+name+'(')),'old inline owner still exists: '+name);
assert.ok(codeText.includes('const GENS_CAPTURE_BATTLE_SAVE_KEY="gensrpg_capture_battle_current_v1";'),'original save key preserved');
assert.ok(codeText.includes('let gensPendingCaptureBattleSetup=null;'),'combat setup state preserved');
function calculate(text){
  const context=vm.createContext({console,Math,localStorage:{}});
  vm.runInContext(text,context,{timeout:1000});
  const targetMode=effects=>vm.runInContext('gensCaptureAbilityTargetMode('+JSON.stringify({effects})+')',context);
  const otherSide=side=>vm.runInContext('gensCaptureBattleOtherSide('+JSON.stringify(side)+')',context);
  const scenarios=[[{kind:'damage'}],[{kind:'heal'}],[{kind:'buff'}],[{kind:'damage',target:'all_enemies'}],[{kind:'shield'}],[{kind:'hot'}],[]];
  return {targetModes:scenarios.map(targetMode),sides:['A','B'].map(otherSide)};
}
assert.deepEqual(calculate(codeText),calculate(restored.subarray(restored.indexOf(start),restored.indexOf(end,restored.indexOf(start))).toString('utf8')),'owner VM behavior parity');
console.log(JSON.stringify({scenario:'Capture battle core single-owner source relocation',functions:names.length,moduleBytes:moduleBytes.length,baseBlob:original.blob,rollbackExact:true,behaviorParity:true}));
